import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("../../", import.meta.url));
const bundle = await build({ absWorkingDir: root, entryPoints: ["apps/mcp-crm/main.ts"],
  bundle: true, minify: true, format: "iife", target: "es2022", write: false,
  outfile: "crm-app.js", legalComments: "inline" });
const js = bundle.outputFiles.find((file) => file.path.endsWith(".js"))?.text;
const css = bundle.outputFiles.find((file) => file.path.endsWith(".css"))?.text;
if (!js || !css) throw new Error("CRM App bundle is missing JavaScript or styles");
const template = await readFile(resolve(root, "apps/mcp-crm/index.html"), "utf8");
const html = template.replace("<!-- CRM_APP_STYLES -->", () => `<style>${css.replace(/<\/style/gi, "<\\/style")}</style>`)
  .replace("<!-- CRM_APP_SCRIPT -->", () => `<script>${js.replace(/<\/script/gi, "<\\/script")}</script>`);
const target = resolve(root, "deploy/annotation/src/mcp-app.ts");
await writeFile(target, `// Generated by apps/mcp-crm/build.mjs. Edit the app source, then rebuild.\nexport const CRM_APP_HTML = ${JSON.stringify(html)};\n`);
console.log(`Built hosted CRM App (${Buffer.byteLength(html)} bytes): ${target}`);
